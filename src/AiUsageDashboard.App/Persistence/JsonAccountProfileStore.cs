	private async Task<AccountProfileLoadResult> RestoreBackupAsync(
		byte[] backupContents,
		string backupFingerprint,
		ParsedSettingsDocument backupDocument,
		string? primaryFingerprint,
		CancellationToken cancellationToken)
	{
		string? directory = Path.GetDirectoryName(_filePath);

		if (directory is null)
		{
			string unavailableMessage = UiText.Get("Persistence.AccountsInvalidPathEditingBlocked");
			BlockSaving(unavailableMessage);
			_isInitialized = true;
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.Unavailable,
				CanSave: false,
				unavailableMessage);
		}

		string temporaryPath = Path.Combine(
			directory,
			$".{Path.GetFileName(_filePath)}.{Guid.NewGuid():N}.restore.tmp");
		string? recoveryPath = primaryFingerprint is null
			? null
			: CreateRecoveryPath(_filePath);

		try
		{
			bool backupExists = await FileExistsAsync(
				BackupFilePath,
				cancellationToken).ConfigureAwait(false);

			if (!backupExists ||
				!string.Equals(
					ComputeFingerprint(await ReadSettingsFileAsync(
						BackupFilePath,
						cancellationToken)),
					backupFingerprint,
					StringComparison.Ordinal))
			{
				throw new IOException(UiText.Get("Persistence.AccountsBackupChangedDuringRestore"));
			}

			bool primaryExists = await FileExistsAsync(
				_filePath,
				cancellationToken).ConfigureAwait(false);

			if (primaryFingerprint is null)
			{
				if (primaryExists)
				{
					throw new IOException(UiText.Get("Persistence.AccountsCreatedDuringRestore"));
				}
			}
			else if (!primaryExists ||
				!string.Equals(
					ComputeFingerprint(await ReadSettingsFileAsync(
						_filePath,
						cancellationToken)),
					primaryFingerprint,
					StringComparison.Ordinal))
			{
				throw new IOException(UiText.Get("Persistence.AccountsChangedDuringRestore"));
			}

			await WriteFileDurablyAsync(
				temporaryPath,
				backupContents,
				cancellationToken).ConfigureAwait(false);

			if (primaryFingerprint is null)
			{
				await Task.Run(
					() => MoveFileSafely(temporaryPath, _filePath),
					CancellationToken.None).ConfigureAwait(false);
			}
			else
			{
				await Task.Run(
					() => ReplaceFileSafely(
						temporaryPath,
						_filePath,
						recoveryPath),
					CancellationToken.None).ConfigureAwait(false);
			}
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			string unavailableMessage = UiText.Get("Persistence.AccountsBackupRestoreFailed");
			BlockSaving(unavailableMessage);
			_isInitialized = true;
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.Unavailable,
				CanSave: false,
				unavailableMessage);
		}
		finally
		{
			await TryDeleteTemporaryFileAsync(temporaryPath).ConfigureAwait(false);
		}

		SetLoadedFileState(fileExisted: true, fingerprint: backupFingerprint);
		_isInitialized = true;

		if (backupDocument.SchemaVersion > CurrentSchemaVersion)
		{
			string message = UiText.Get("Persistence.AccountsRestoredNewerBackup");
			BlockSaving(message);
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.UnsupportedVersion,
				CanSave: false,
				message,
				recoveryPath);
		}

		EnableSaving();
		string recoveredMessage = primaryFingerprint is null
			? UiText.Get("Persistence.AccountsMissingRestored")
			: UiText.Get("Persistence.AccountsCorruptRestored");
		return new AccountProfileLoadResult(
			backupDocument.Accounts!,
			AccountProfileLoadStatus.RecoveredCorruptFile,
			CanSave: true,
			recoveredMessage,
			recoveryPath);
	}

	private static string CreateRecoveryPath(string filePath)
	{
		string directory = Path.GetDirectoryName(filePath)!;
		string fileNameWithoutExtension = Path.GetFileNameWithoutExtension(filePath);
		string extension = Path.GetExtension(filePath);
		return Path.Combine(
			directory,
			$"{fileNameWithoutExtension}.corrupt-{DateTimeOffset.UtcNow:yyyyMMddTHHmmssfffZ}-{Guid.NewGuid():N}{extension}");
	}

	private async Task<string> SaveDocumentAsync(
		SettingsDocument document,
		CancellationToken cancellationToken)
	{
		string? directory = Path.GetDirectoryName(_filePath);

		if (directory is null)
		{
			throw new AccountProfileStoreException(UiText.Get("Persistence.AccountsInvalidPath"));
		}

		await CreateDirectoryAsync(directory, cancellationToken)
			.ConfigureAwait(false);
		byte[] serializedDocument = JsonSerializer.SerializeToUtf8Bytes(
			document,
			SerializerOptions);

		if (serializedDocument.Length > MaximumSettingsFileSize)
		{
			throw new AccountProfileStoreException(
				UiText.Get("Persistence.AccountsSaveTooLarge"));
		}

		string fingerprint = ComputeFingerprint(serializedDocument);
		string temporaryPath = Path.Combine(
			directory,
			$".{Path.GetFileName(_filePath)}.{Guid.NewGuid():N}.tmp");
		string temporaryBackupPath = Path.Combine(
			directory,
			$".{Path.GetFileName(BackupFilePath)}.{Guid.NewGuid():N}.tmp");

		try
		{
			await WriteFileDurablyAsync(
				temporaryPath,
				serializedDocument,
				cancellationToken).ConfigureAwait(false);
			await WriteFileDurablyAsync(
				temporaryBackupPath,
				serializedDocument,
				cancellationToken).ConfigureAwait(false);
			await RecordPortableImportPreparedWriteAsync(
				_filePath,
				temporaryPath,
				cancellationToken).ConfigureAwait(false);

			await Task.Run(
				() =>
				{
					if (FileExistsSafely(_filePath))
					{
						ReplaceFileSafely(
							temporaryPath,
							_filePath,
							destinationBackupFileName: null);
					}
					else
					{
						MoveFileSafely(temporaryPath, _filePath);
					}
				},
				CancellationToken.None).ConfigureAwait(false);

			SetLoadedFileState(fileExisted: true, fingerprint: fingerprint);

			try
			{
				await RecordPortableImportPreparedWriteAsync(
					BackupFilePath,
					temporaryBackupPath,
					cancellationToken).ConfigureAwait(false);
				await Task.Run(
					() =>
					{
						if (FileExistsSafely(BackupFilePath))
						{
							ReplaceFileSafely(
								temporaryBackupPath,
								BackupFilePath,
								destinationBackupFileName: null);
						}
						else
						{
							MoveFileSafely(
								temporaryBackupPath,
								BackupFilePath);
						}
					},
					CancellationToken.None).ConfigureAwait(false);
			}
			catch (Exception exception) when (
				(exception is IOException) ||
				(exception is UnauthorizedAccessException) ||
				(exception is NotSupportedException))
			{
				throw new AccountProfileStoreException(
					UiText.Get("Persistence.AccountBackupUpdateFailedCommitted"),
					exception,
					hasCommittedChanges: true);
			}
		}
		finally
		{
			await Task.WhenAll(
				TryDeleteTemporaryFileAsync(temporaryPath),
				TryDeleteTemporaryFileAsync(temporaryBackupPath))
				.ConfigureAwait(false);
		}

		return fingerprint;
	}

	private Task RecordPortableImportPreparedWriteAsync(
		string destinationFilePath,
		string preparedFilePath,
		CancellationToken cancellationToken)
	{
		return _portableSettingsImportWriteTracker is null
			? Task.CompletedTask
			: _portableSettingsImportWriteTracker.RecordPreparedWriteAsync(
				destinationFilePath,
				preparedFilePath,
				cancellationToken);
	}

