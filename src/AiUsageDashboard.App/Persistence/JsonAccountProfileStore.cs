	private AccountProfileLoadResult RecoverCorruptFile(
		string? expectedFingerprint,
		string? invalidBackupFingerprint)
	{
		string? directory = Path.GetDirectoryName(_filePath);

		if (directory is null)
		{
			string unavailableMessage = UiText.Get("Persistence.AccountsInvalidPathEditingBlocked");
			BlockSaving(unavailableMessage);
			_isInitialized = true;
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.Unavailable,
				CanSave: false,
				unavailableMessage);
		}

		string recoveryPath = CreateRecoveryPath(_filePath);
		string? backupRecoveryPath = invalidBackupFingerprint is null
			? null
			: CreateRecoveryPath(BackupFilePath);

		try
		{
			if ((expectedFingerprint is null) ||
				!FileExistsSafely(_filePath) ||
				!string.Equals(
					ComputeFingerprint(ReadSettingsFile(_filePath)),
					expectedFingerprint,
					StringComparison.Ordinal))
			{
				string changedMessage = UiText.Get("Persistence.AccountsChangedDuringRead");
				BlockSaving(changedMessage);
				_isInitialized = true;
				return new AccountProfileLoadResult(
					Array.Empty<AccountProfile>(),
					AccountProfileLoadStatus.Unavailable,
					CanSave: false,
					changedMessage);
			}

			if (invalidBackupFingerprint is not null)
			{
				if (!FileExistsSafely(BackupFilePath) ||
					!string.Equals(
						ComputeFingerprint(ReadSettingsFile(BackupFilePath)),
						invalidBackupFingerprint,
						StringComparison.Ordinal))
				{
					string changedMessage = UiText.Get("Persistence.AccountsBackupChangedDuringRead");
					BlockSaving(changedMessage);
					_isInitialized = true;
					return new AccountProfileLoadResult(
						Array.Empty<AccountProfile>(),
						AccountProfileLoadStatus.Unavailable,
						CanSave: false,
						changedMessage);
				}

				MoveFileSafely(BackupFilePath, backupRecoveryPath!);
			}

			MoveFileSafely(_filePath, recoveryPath);
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			string unavailableMessage = UiText.Get("Persistence.AccountsCorruptCopyUnavailable");
			BlockSaving(unavailableMessage);
			_isInitialized = true;
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.Unavailable,
				CanSave: false,
				unavailableMessage);
		}

		EnableSaving();
		SetLoadedFileState(fileExisted: false, fingerprint: null);
		_isInitialized = true;
		string message = invalidBackupFingerprint is null
			? UiText.Get("Persistence.AccountsInvalidPreservedEmpty")
			: UiText.Get("Persistence.AccountsBothInvalidPreservedEmpty");
		return new AccountProfileLoadResult(
			Array.Empty<AccountProfile>(),
			AccountProfileLoadStatus.RecoveredCorruptFile,
			CanSave: true,
			message,
			recoveryPath);
	}

