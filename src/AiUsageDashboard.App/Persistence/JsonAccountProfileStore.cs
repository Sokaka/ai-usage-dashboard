public sealed class JsonAccountProfileStore : IAccountProfileStore
{
	private sealed record PortableImportLoadedFileState(
		bool FileExisted,
		string? Fingerprint);

	private enum BackupValidationStatus
	{
		Available,
		Blocked,
		FutureVersion,
		Oversized,
		Unavailable
	}

	private sealed record AccountDocument(
		Guid Id,
		ProviderKind? Provider,
		string? DisplayName,
		bool? IsEnabled,
		string? ProviderAccountIdentity = null,
		bool? HasAcceptedClaudeQuotaRisk = null,
		bool? ShowSubscriptionContext = null);

	private sealed record SettingsDocument(
		int SchemaVersion,
		List<AccountDocument?>? Accounts);

	private sealed record ParsedSettingsDocument(
		int SchemaVersion,
		IReadOnlyList<AccountProfile>? Accounts);

	private sealed class SettingsFileTooLargeException : IOException
	{
		public SettingsFileTooLargeException()
			: base(UiText.Get("Persistence.AccountsFileTooLarge"))
		{
		}
	}

	private const string BackupFileSuffix = ".bak";
	private const int AutoGeneratedDisplayNameSchemaVersion = 2;
	private const int AutoGeneratedDisplayNameLastSchemaVersion = 4;
	private const int ClaudeQuotaRiskSchemaVersion = 4;
	private const int CurrentSchemaVersion = 7;
	private const int LegacySchemaVersion = 1;
	private const int MaximumAccountCount = 256;
	private const int MaximumDisplayNameLength = 80;
	private const int MaximumSettingsFileSize = 1024 * 1024;
	private const string ManagedPathDescription = "The account profile path";
	private const int SubscriptionContextSchemaVersion = 7;
	private static readonly ConcurrentDictionary<string, SemaphoreSlim> FileGates =
		new(StringComparer.OrdinalIgnoreCase);
	private static readonly JsonSerializerOptions SerializerOptions = CreateSerializerOptions();
	private readonly SemaphoreSlim _fileGate;
	private readonly string _filePath;
	private readonly object _portableImportStateSync = new();
	private bool _canSave = true;
	private bool _isInitialized;
	private bool _loadedFileExisted;
	private string? _loadedFileFingerprint;
	private PortableImportLoadedFileState? _portableImportLoadedFileState;
	private readonly PortableSettingsImportWriteTracker?
		_portableSettingsImportWriteTracker;
	private readonly Action<string, string, Exception?> _reportDiagnostic;
	private string? _saveBlockedMessage;

	public string FilePath => _filePath;

	private string BackupFilePath => $"{_filePath}{BackupFileSuffix}";

	public JsonAccountProfileStore(string filePath)
		: this(filePath, portableSettingsImportWriteTracker: null)
	{
	}

	internal JsonAccountProfileStore(
		string filePath,
		PortableSettingsImportWriteTracker?
			portableSettingsImportWriteTracker,
		Action<string, string, Exception?>? reportDiagnostic = null)
	{
		ArgumentException.ThrowIfNullOrWhiteSpace(filePath);
		_filePath = Path.GetFullPath(filePath);
		_fileGate = FileGates.GetOrAdd(_filePath, _ => new SemaphoreSlim(1, 1));
		_portableSettingsImportWriteTracker =
			portableSettingsImportWriteTracker;
		_reportDiagnostic = reportDiagnostic ?? ((_, _, _) => { });
	}

	public async Task<AccountProfileLoadResult> LoadAsync(
		CancellationToken cancellationToken = default)
	{
		await _fileGate.WaitAsync(cancellationToken);

		try
		{
			return await LoadCoreAsync(cancellationToken);
		}
		finally
		{
			_fileGate.Release();
		}
	}

	public async Task SaveAsync(
		IReadOnlyList<AccountProfile> accounts,
		CancellationToken cancellationToken = default)
	{
		ArgumentNullException.ThrowIfNull(accounts);
		await _fileGate.WaitAsync(cancellationToken);

		try
		{
			if (!_isInitialized)
			{
				AccountProfileLoadResult loadResult = await LoadCoreAsync(cancellationToken);

				if (!loadResult.CanSave)
				{
					throw new AccountProfileStoreException(
						loadResult.Message ?? UiText.Get("Persistence.AccountsNotWritable"));
				}
			}

			if (!_canSave)
			{
				throw new AccountProfileStoreException(
					_saveBlockedMessage ?? UiText.Get("Persistence.AccountsNotWritable"));
			}

			SettingsDocument document = CreateDocument(accounts);
			await VerifyFileHasNotChangedAsync(cancellationToken);
			await VerifyBackupCanBeReplacedAsync(cancellationToken);
			string fingerprint = await SaveDocumentAsync(document, cancellationToken);
			SetLoadedFileState(fileExisted: true, fingerprint: fingerprint);
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (AccountProfileStoreException)
		{
			throw;
		}
		catch (ArgumentException)
		{
			throw;
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			throw new AccountProfileStoreException(
				UiText.Get("Persistence.AccountSaveFailed"),
				exception);
		}
		finally
		{
			_fileGate.Release();
		}
	}

	internal async Task BeginPortableImportTransactionAsync(
		CancellationToken cancellationToken = default)
	{
		await _fileGate.WaitAsync(cancellationToken).ConfigureAwait(false);

		try
		{
			lock (_portableImportStateSync)
			{
				_portableImportLoadedFileState = _isInitialized
					? new PortableImportLoadedFileState(
						_loadedFileExisted,
						_loadedFileFingerprint)
					: null;
			}
		}
		finally
		{
			_fileGate.Release();
		}
	}

	internal async Task SynchronizeLoadedFileStateAfterExternalRestoreAsync(
		CancellationToken cancellationToken = default)
	{
		await _fileGate.WaitAsync(cancellationToken).ConfigureAwait(false);

		try
		{
			PortableImportLoadedFileState? baselineState;

			lock (_portableImportStateSync)
			{
				baselineState = _portableImportLoadedFileState;
			}

			// Startup recovery precedes LoadAsync. During an in-session rollback,
			// restore the loaded state that matched the UI before the transaction.
			// A conditional rollback may deliberately preserve a later external
			// file; adopting that file's fingerprint here would let the unchanged UI
			// overwrite it on its next save without triggering stale-writer defense.
			if (!_isInitialized ||
				(baselineState is null) ||
				((_loadedFileExisted == baselineState.FileExisted) &&
					string.Equals(
						_loadedFileFingerprint,
						baselineState.Fingerprint,
						StringComparison.Ordinal)))
			{
				return;
			}

			SetLoadedFileState(
				baselineState.FileExisted,
				baselineState.Fingerprint);
		}
		finally
		{
			_fileGate.Release();
		}
	}

	internal void CompletePortableImportTransaction()
	{
		lock (_portableImportStateSync)
		{
			_portableImportLoadedFileState = null;
		}
	}

	private static SettingsDocument CreateDocument(
		IReadOnlyList<AccountProfile> accounts)
	{
		if (accounts.Count > MaximumAccountCount)
		{
			throw new ArgumentException(
				UiText.Format("Persistence.AccountLimit", MaximumAccountCount),
				nameof(accounts));
		}

		HashSet<Guid> accountIds = new();
		Dictionary<ProviderKind, HashSet<string>> providerAccountIdentities = new();
		List<AccountDocument?> accountDocuments = new(accounts.Count);

		foreach (AccountProfile account in accounts)
		{
			if (account.Id == Guid.Empty)
			{
				throw new ArgumentException(UiText.Get("Persistence.AccountIdEmpty"), nameof(accounts));
			}

			if (!accountIds.Add(account.Id))
			{
				throw new ArgumentException(UiText.Get("Persistence.DuplicateAccount"), nameof(accounts));
			}

			if (!Enum.IsDefined(typeof(ProviderKind), account.Provider))
			{
				throw new ArgumentException(UiText.Get("Persistence.UnsupportedProvider"), nameof(accounts));
			}

			string displayName = NormalizeDisplayName(account.DisplayName, nameof(accounts));
			string? providerAccountIdentity = NormalizeProviderAccountIdentity(
				account.Provider,
				account.ProviderAccountIdentity,
				nameof(accounts));
			EnsureUniqueProviderAccountIdentity(
				providerAccountIdentities,
				account.Provider,
				providerAccountIdentity,
				nameof(accounts));
			accountDocuments.Add(new AccountDocument(
				account.Id,
				account.Provider,
				displayName,
				account.IsEnabled,
				providerAccountIdentity,
				account.Provider == ProviderKind.Claude &&
					account.HasAcceptedClaudeQuotaRisk,
				account.ShowSubscriptionContext));
		}

		return new SettingsDocument(CurrentSchemaVersion, accountDocuments);
	}

	private static JsonSerializerOptions CreateSerializerOptions()
	{
		JsonSerializerOptions options = new()
		{
			MaxDepth = 16,
			DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
			PropertyNameCaseInsensitive = false,
			PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
			UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
			WriteIndented = true
		};
		options.Converters.Add(new JsonStringEnumConverter(
			namingPolicy: null,
			allowIntegerValues: false));
		return options;
	}

	private static string ComputeFingerprint(byte[] fileContents)
	{
		return Convert.ToHexString(SHA256.HashData(fileContents));
	}

	private static Task CreateDirectoryAsync(
		string directoryPath,
		CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();
		return Task.Run(
			() => ManagedFilePathGuard.CreateDirectoryAndEnsureSafe(
				directoryPath,
				ManagedPathDescription),
			cancellationToken);
	}

	private static Task<bool> FileExistsAsync(
		string filePath,
		CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();
		return Task.Run(
			() => FileExistsSafely(filePath),
			cancellationToken);
	}

	private static bool FileExistsSafely(string filePath)
	{
		ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
			filePath,
			ManagedPathDescription);
		return File.Exists(filePath);
	}

	private static byte[] ReadSettingsFile(string filePath)
	{
		ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
			filePath,
			ManagedPathDescription);
		using FileStream stream = new(
			filePath,
			FileMode.Open,
			FileAccess.Read,
			FileShare.Read,
			bufferSize: 4096,
			FileOptions.SequentialScan);
		int fileLength = ValidateSettingsFileLength(stream.Length);
		byte[] fileContents = GC.AllocateUninitializedArray<byte>(fileLength);
		stream.ReadExactly(fileContents);
		return fileContents;
	}

	private static Task<byte[]> ReadSettingsFileAsync(
		string filePath,
		CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();
		return Task.Run(
			async () =>
			{
				ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
					filePath,
					ManagedPathDescription);
				await using FileStream stream = new(
					filePath,
					FileMode.Open,
					FileAccess.Read,
					FileShare.Read,
					bufferSize: 4096,
					FileOptions.Asynchronous | FileOptions.SequentialScan);
				int fileLength = ValidateSettingsFileLength(stream.Length);
				byte[] fileContents =
					GC.AllocateUninitializedArray<byte>(fileLength);
				await stream.ReadExactlyAsync(fileContents, cancellationToken)
					.ConfigureAwait(false);
				return fileContents;
			},
			cancellationToken);
	}

	private static int ValidateSettingsFileLength(long fileLength)
	{
		if (fileLength > MaximumSettingsFileSize)
		{
			throw new SettingsFileTooLargeException();
		}

		return checked((int)fileLength);
	}

	private static ParsedSettingsDocument ParseSettingsDocument(byte[] fileContents)
	{
		using JsonDocument parsedDocument = JsonDocument.Parse(
			fileContents,
			new JsonDocumentOptions
			{
				MaxDepth = 16
			});

		if (parsedDocument.RootElement.ValueKind != JsonValueKind.Object)
		{
			throw new InvalidDataException(UiText.Get("Persistence.AccountRootNotObject"));
		}

		if (!parsedDocument.RootElement.TryGetProperty(
			"schemaVersion",
			out JsonElement schemaVersionElement) ||
			schemaVersionElement.ValueKind != JsonValueKind.Number ||
			!schemaVersionElement.TryGetInt32(out int schemaVersion))
		{
			throw new InvalidDataException(UiText.Get("Persistence.SchemaVersionMissing"));
		}

		if (schemaVersion > CurrentSchemaVersion)
		{
			return new ParsedSettingsDocument(schemaVersion, Accounts: null);
		}

		if (schemaVersion < LegacySchemaVersion)
		{
			throw new InvalidDataException(UiText.Get("Persistence.InvalidSchemaVersion"));
		}

		if (!parsedDocument.RootElement.TryGetProperty(
				"accounts",
				out JsonElement accountsElement) ||
			(accountsElement.ValueKind != JsonValueKind.Array) ||
			(accountsElement.GetArrayLength() > MaximumAccountCount))
		{
			throw new InvalidDataException(UiText.Get("Persistence.InvalidAccountList"));
		}

		SettingsDocument? document = JsonSerializer.Deserialize<SettingsDocument>(
			fileContents,
			SerializerOptions);

		if (document is null)
		{
			throw new InvalidDataException(UiText.Get("Persistence.AccountsContentEmpty"));
		}

		IReadOnlyList<AccountProfile> accounts = ReadAccounts(document);

		if (schemaVersion == LegacySchemaVersion)
		{
			accounts = accounts
				.OrderBy(account => account.Provider)
				.ThenBy(
					account => account.DisplayName,
					StringComparer.CurrentCultureIgnoreCase)
				.ToArray();
		}

		if ((schemaVersion >= AutoGeneratedDisplayNameSchemaVersion) &&
			(schemaVersion <= AutoGeneratedDisplayNameLastSchemaVersion))
		{
			accounts = accounts
				.Select(account => IsLegacyAutoGeneratedDisplayName(
					account.Provider,
					account.DisplayName)
					? account with { DisplayName = string.Empty }
					: account)
				.ToArray();
		}

		return new ParsedSettingsDocument(schemaVersion, accounts);
	}

	private static IReadOnlyList<AccountProfile> ReadAccounts(
		SettingsDocument document)
	{
		if ((document.Accounts is null) ||
			(document.Accounts.Count > MaximumAccountCount))
		{
			throw new InvalidDataException(UiText.Get("Persistence.InvalidAccountList"));
		}

		HashSet<Guid> accountIds = new();
		Dictionary<ProviderKind, HashSet<string>> providerAccountIdentities = new();
		List<AccountProfile> accounts = new(document.Accounts.Count);

		foreach (AccountDocument? account in document.Accounts)
		{
			if (account is null)
			{
				throw new InvalidDataException(UiText.Get("Persistence.AccountEntryEmpty"));
			}

			if (account.Id == Guid.Empty)
			{
				throw new InvalidDataException(UiText.Get("Persistence.AccountIdEmpty"));
			}

			if (!accountIds.Add(account.Id))
			{
				throw new InvalidDataException(UiText.Get("Persistence.DuplicateAccount"));
			}

			if ((account.Provider is null) ||
				!Enum.IsDefined(typeof(ProviderKind), account.Provider.Value))
			{
				throw new InvalidDataException(UiText.Get("Persistence.AccountProviderMissing"));
			}

			if (account.IsEnabled is null)
			{
				throw new InvalidDataException(UiText.Get("Persistence.AccountUsageCheckingMissing"));
			}

			if ((document.SchemaVersion >= ClaudeQuotaRiskSchemaVersion) &&
				(account.HasAcceptedClaudeQuotaRisk is null))
			{
				throw new InvalidDataException(
					UiText.Get("Persistence.ClaudeQuotaRiskMissing"));
			}

			if ((document.SchemaVersion >= SubscriptionContextSchemaVersion) &&
				(account.ShowSubscriptionContext is null))
			{
				throw new InvalidDataException(
					UiText.Get("Persistence.SubscriptionContextMissing"));
			}

			string displayName = NormalizeDisplayName(account.DisplayName, null);

			string? providerAccountIdentity = NormalizeProviderAccountIdentity(
				account.Provider.Value,
				account.ProviderAccountIdentity,
				parameterName: null);
			bool hasAcceptedClaudeQuotaRisk =
				(document.SchemaVersion >= ClaudeQuotaRiskSchemaVersion) &&
				(account.Provider.Value == ProviderKind.Claude) &&
				(account.HasAcceptedClaudeQuotaRisk == true);
			EnsureUniqueProviderAccountIdentity(
				providerAccountIdentities,
				account.Provider.Value,
				providerAccountIdentity,
				parameterName: null);
			accounts.Add(new AccountProfile(
				account.Id,
				account.Provider.Value,
				displayName,
				account.IsEnabled.Value,
				providerAccountIdentity,
				hasAcceptedClaudeQuotaRisk,
				ShowSubscriptionContext:
					document.SchemaVersion >= SubscriptionContextSchemaVersion &&
					(account.ShowSubscriptionContext == true)));
		}

		return accounts;
	}

	private static string NormalizeDisplayName(
		string? displayName,
		string? parameterName)
	{
		if (displayName is null)
		{
			if (parameterName is not null)
			{
				throw new ArgumentException(UiText.Get("Persistence.DisplayNameExplicitNull"), parameterName);
			}

			throw new InvalidDataException(UiText.Get("Persistence.DisplayNameExplicitNull"));
		}

		string normalizedDisplayName = displayName.Trim();

		if (normalizedDisplayName.Length > MaximumDisplayNameLength)
		{
			if (parameterName is not null)
			{
				throw new ArgumentException(
					UiText.Format("Persistence.DisplayNameLimit", MaximumDisplayNameLength),
					parameterName);
			}

			throw new InvalidDataException(UiText.Get("Persistence.DisplayNameTooLong"));
		}

		if (normalizedDisplayName.Any(char.IsControl))
		{
			if (parameterName is not null)
			{
				throw new ArgumentException(
					UiText.Get("Persistence.DisplayNameControlCharacters"),
					parameterName);
			}

			throw new InvalidDataException(UiText.Get("Persistence.DisplayNameContainsControls"));
		}

		return normalizedDisplayName;
	}

	private static bool IsLegacyAutoGeneratedDisplayName(
		ProviderKind provider,
		string displayName)
	{
		string providerDisplayName = provider switch
		{
			ProviderKind.Claude => "Claude",
			ProviderKind.Codex => "Codex",
			ProviderKind.Copilot => "GitHub Copilot",
			ProviderKind.Antigravity => "Antigravity",
			ProviderKind.Grok => "Grok",
			_ => throw new ArgumentOutOfRangeException(nameof(provider))
		};

		if (string.Equals(
				displayName,
				providerDisplayName,
				StringComparison.Ordinal))
		{
			return true;
		}

		string numberedPrefix = $"{providerDisplayName} ";

		if (!displayName.StartsWith(numberedPrefix, StringComparison.Ordinal))
		{
			return false;
		}

		ReadOnlySpan<char> suffix = displayName.AsSpan(numberedPrefix.Length);

		if ((suffix.Length == 0) || (suffix[0] == '0'))
		{
			return false;
		}

		foreach (char character in suffix)
		{
			if ((character < '0') || (character > '9'))
			{
				return false;
			}
		}

		return (suffix.Length > 1) || (suffix[0] >= '2');
	}

	private static void EnsureUniqueProviderAccountIdentity(
		Dictionary<ProviderKind, HashSet<string>> providerAccountIdentities,
		ProviderKind provider,
		string? providerAccountIdentity,
		string? parameterName)
	{
		if (providerAccountIdentity is null)
		{
			return;
		}

		if (!providerAccountIdentities.TryGetValue(
				provider,
				out HashSet<string>? identities))
		{
			identities = new HashSet<string>(
				ProviderAccountIdentityRules.Comparer);
			providerAccountIdentities.Add(provider, identities);
		}

		if (identities.Add(providerAccountIdentity))
		{
			return;
		}

		if (parameterName is not null)
		{
			throw new ArgumentException(
				UiText.Get("Persistence.DuplicateConnectedAccount"),
				parameterName);
		}

		throw new InvalidDataException(
			UiText.Get("Persistence.DuplicateConnectedAccount"));
	}

	private static string? NormalizeProviderAccountIdentity(
		ProviderKind provider,
		string? providerAccountIdentity,
		string? parameterName)
	{
		if (ProviderAccountIdentityRules.TryNormalize(
				providerAccountIdentity,
				out string? normalizedIdentity))
		{
			if ((provider != ProviderKind.Grok) ||
				(normalizedIdentity is null) ||
				GrokAccountBinding.TryNormalizePublicBindingIdentity(
					providerAccountIdentity,
					out normalizedIdentity))
			{
				return normalizedIdentity;
			}
		}

		if (parameterName is not null)
		{
			throw new ArgumentException(
				provider == ProviderKind.Grok
					? UiText.Get("Persistence.InvalidGrokBinding")
					: UiText.Get("Persistence.InvalidAccountIdentity"),
				parameterName);
		}

		throw new InvalidDataException(
			provider == ProviderKind.Grok
				? UiText.Get("Persistence.InvalidGrokBinding")
				: UiText.Get("Persistence.InvalidAccountIdentity"));
	}

	private async Task<AccountProfileLoadResult> LoadCoreAsync(
		CancellationToken cancellationToken)
	{
		_isInitialized = false;
		SetLoadedFileState(fileExisted: false, fingerprint: null);
		EnableSaving();

		string? loadedFileFingerprint = null;

		try
		{
			if (!await FileExistsAsync(_filePath, cancellationToken)
					.ConfigureAwait(false))
			{
				return await LoadMissingPrimaryAsync(cancellationToken);
			}

			byte[] fileContents = await ReadSettingsFileAsync(
				_filePath,
				cancellationToken);
			loadedFileFingerprint = ComputeFingerprint(fileContents);
			ParsedSettingsDocument document = ParseSettingsDocument(fileContents);

			if (document.SchemaVersion > CurrentSchemaVersion)
			{
				string unsupportedVersionMessage =
					UiText.Get("Persistence.AccountsNewerSchema");
				BlockSaving(unsupportedVersionMessage);
				SetLoadedFileState(fileExisted: true, fingerprint: loadedFileFingerprint);
				_isInitialized = true;
				return new AccountProfileLoadResult(
					Array.Empty<AccountProfile>(),
					AccountProfileLoadStatus.UnsupportedVersion,
					CanSave: false,
					unsupportedVersionMessage);
			}

			BackupValidationStatus backupStatus = await TryEnsureValidatedBackupAsync(
				fileContents,
				cancellationToken);
			SetLoadedFileState(fileExisted: true, fingerprint: loadedFileFingerprint);
			_isInitialized = true;

			if (backupStatus == BackupValidationStatus.Blocked)
			{
				string blockedBackupMessage =
					UiText.Get("Persistence.AccountsLoadedBackupUnreadable");
				BlockSaving(blockedBackupMessage);
				return new AccountProfileLoadResult(
					document.Accounts!,
					AccountProfileLoadStatus.Loaded,
					CanSave: false,
					blockedBackupMessage);
			}

			if (backupStatus == BackupValidationStatus.FutureVersion)
			{
				string futureBackupMessage =
					UiText.Get("Persistence.AccountsLoadedBackupNewerSchema");
				BlockSaving(futureBackupMessage);
				return new AccountProfileLoadResult(
					document.Accounts!,
					AccountProfileLoadStatus.Loaded,
					CanSave: false,
					futureBackupMessage);
			}

			if (backupStatus == BackupValidationStatus.Oversized)
			{
				string oversizedBackupMessage =
					UiText.Get("Persistence.AccountsLoadedBackupTooLarge");
				BlockSaving(oversizedBackupMessage);
				return new AccountProfileLoadResult(
					document.Accounts!,
					AccountProfileLoadStatus.Loaded,
					CanSave: false,
					oversizedBackupMessage);
			}

			string? backupMessage = backupStatus == BackupValidationStatus.Available
				? null
				: UiText.Get("Persistence.AccountsLoadedBackupRepairFailed");
			return new AccountProfileLoadResult(
				document.Accounts!,
				AccountProfileLoadStatus.Loaded,
				CanSave: true,
				backupMessage);
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (SettingsFileTooLargeException)
		{
			string message =
				UiText.Get("Persistence.AccountsTooLargeEditingBlocked");
			BlockSaving(message);
			_isInitialized = true;
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.Unavailable,
				CanSave: false,
				message);
		}
		catch (Exception exception) when (
			(exception is JsonException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			return await RecoverCorruptFileAsync(
				loadedFileFingerprint,
				cancellationToken);
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException))
		{
			ReportDiagnostic(
				"account-profile-load",
				"stage=primary-read;result=unavailable",
				exception);
			string message = UiText.Get("Persistence.AccountsUnreadableEditingBlocked");
			BlockSaving(message);
			_isInitialized = true;
			return new AccountProfileLoadResult(
				Array.Empty<AccountProfile>(),
				AccountProfileLoadStatus.Unavailable,
				CanSave: false,
				message);
		}
	}

	private async Task<BackupValidationStatus> TryEnsureValidatedBackupAsync(
		byte[] validatedFileContents,
		CancellationToken cancellationToken)
	{
		bool backupExists;

		try
		{
			backupExists = await FileExistsAsync(BackupFilePath, cancellationToken)
				.ConfigureAwait(false);
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException))
		{
			ReportDiagnostic(
				"account-profile-load",
				"stage=backup-validation;result=unavailable",
				exception);
			return BackupValidationStatus.Blocked;
		}

		if (!backupExists)
		{
			bool isBackupCreated = await TryCreateBackupAsync(
				validatedFileContents,
				cancellationToken);
			return isBackupCreated
				? BackupValidationStatus.Available
				: BackupValidationStatus.Unavailable;
		}

		string? backupFingerprint = null;

		try
		{
			byte[] backupContents = await ReadSettingsFileAsync(
				BackupFilePath,
				cancellationToken);
			backupFingerprint = ComputeFingerprint(backupContents);
			ParsedSettingsDocument backupDocument = ParseSettingsDocument(backupContents);

			if (backupDocument.SchemaVersion > CurrentSchemaVersion)
			{
				return BackupValidationStatus.FutureVersion;
			}

			if (string.Equals(
				backupFingerprint,
				ComputeFingerprint(validatedFileContents),
				StringComparison.Ordinal))
			{
				return BackupValidationStatus.Available;
			}

			bool isBackupRepaired = await TryReplaceBackupAsync(
				validatedFileContents,
				backupFingerprint,
				preserveReplacedBackup: false,
				cancellationToken);
			return isBackupRepaired
				? BackupValidationStatus.Available
				: BackupValidationStatus.Unavailable;
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (SettingsFileTooLargeException)
		{
			return BackupValidationStatus.Oversized;
		}
		catch (Exception exception) when (
			(exception is JsonException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			bool isBackupRepaired = await TryReplaceBackupAsync(
				validatedFileContents,
				backupFingerprint,
				preserveReplacedBackup: true,
				cancellationToken);
			return isBackupRepaired
				? BackupValidationStatus.Available
				: BackupValidationStatus.Unavailable;
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException))
		{
			return BackupValidationStatus.Unavailable;
		}
	}

	private async Task<bool> TryReplaceBackupAsync(
		byte[] validatedFileContents,
		string? expectedBackupFingerprint,
		bool preserveReplacedBackup,
		CancellationToken cancellationToken)
	{
		if (expectedBackupFingerprint is null)
		{
			return false;
		}

		string? directory = Path.GetDirectoryName(_filePath);

		if (directory is null)
		{
			return false;
		}

		string temporaryPath = Path.Combine(
			directory,
			$".{Path.GetFileName(BackupFilePath)}.{Guid.NewGuid():N}.repair.tmp");

		try
		{
			if (!await FileExistsAsync(BackupFilePath, cancellationToken)
					.ConfigureAwait(false))
			{
				return await TryCreateBackupAsync(
					validatedFileContents,
					cancellationToken);
			}

			await WriteFileDurablyAsync(
				temporaryPath,
				validatedFileContents,
				cancellationToken).ConfigureAwait(false);
			byte[] currentBackupContents = await ReadSettingsFileAsync(
				BackupFilePath,
				cancellationToken);

			if (!string.Equals(
				ComputeFingerprint(currentBackupContents),
				expectedBackupFingerprint,
				StringComparison.Ordinal))
			{
				return false;
			}

			string? recoveryPath = preserveReplacedBackup
				? CreateRecoveryPath(BackupFilePath)
				: null;
			await Task.Run(
				() => ReplaceFileSafely(
					temporaryPath,
					BackupFilePath,
					recoveryPath),
				CancellationToken.None).ConfigureAwait(false);
			return true;
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			return false;
		}
		finally
		{
			await TryDeleteTemporaryFileAsync(temporaryPath).ConfigureAwait(false);
		}
	}

	private async Task<bool> TryCreateBackupAsync(
		byte[] validatedFileContents,
		CancellationToken cancellationToken)
	{
		if (await FileExistsAsync(BackupFilePath, cancellationToken)
				.ConfigureAwait(false))
		{
			return false;
		}

		string? directory = Path.GetDirectoryName(_filePath);

		if (directory is null)
		{
			return false;
		}

		string temporaryPath = Path.Combine(
			directory,
			$".{Path.GetFileName(BackupFilePath)}.{Guid.NewGuid():N}.migration.tmp");

		try
		{
			await WriteFileDurablyAsync(
				temporaryPath,
				validatedFileContents,
				cancellationToken).ConfigureAwait(false);

			if (await FileExistsAsync(BackupFilePath, cancellationToken)
					.ConfigureAwait(false))
			{
				return false;
			}

			await Task.Run(
				() => MoveFileSafely(temporaryPath, BackupFilePath),
				CancellationToken.None).ConfigureAwait(false);
			return true;
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException) ||
			(exception is NotSupportedException))
		{
			return false;
		}
		finally
		{
			await TryDeleteTemporaryFileAsync(temporaryPath).ConfigureAwait(false);
		}
	}

