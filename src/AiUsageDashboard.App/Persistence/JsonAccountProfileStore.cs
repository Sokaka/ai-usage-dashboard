	private static void MoveFileSafely(
		string sourceFilePath,
		string destinationFilePath)
	{
		ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
			sourceFilePath,
			ManagedPathDescription);
		ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
			destinationFilePath,
			ManagedPathDescription);
		File.Move(sourceFilePath, destinationFilePath);
	}

	private static void ReplaceFileSafely(
		string sourceFilePath,
		string destinationFilePath,
		string? destinationBackupFileName)
	{
		ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
			sourceFilePath,
			ManagedPathDescription);
		ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
			destinationFilePath,
			ManagedPathDescription);
		if (destinationBackupFileName is not null)
		{
			ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
				destinationBackupFileName,
				ManagedPathDescription);
		}

		File.Replace(
			sourceFilePath,
			destinationFilePath,
			destinationBackupFileName);
	}

	private static Task WriteFileDurablyAsync(
		string filePath,
		byte[] fileContents,
		CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();
		return Task.Run(
			async () =>
			{
				ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
					filePath,
					ManagedPathDescription);
				await using FileStream stream = new(
					filePath,
					FileMode.CreateNew,
					FileAccess.Write,
					FileShare.None,
					bufferSize: 4096,
					FileOptions.Asynchronous | FileOptions.WriteThrough);
				await stream.WriteAsync(fileContents, cancellationToken)
					.ConfigureAwait(false);
				await stream.FlushAsync(cancellationToken).ConfigureAwait(false);
				stream.Flush(flushToDisk: true);
			},
			cancellationToken);
	}

	private static void TryDeleteTemporaryFile(string temporaryPath)
	{
		try
		{
			ManagedFilePathGuard.EnsureExistingFilePathIsSafe(
				temporaryPath,
				ManagedPathDescription);
			File.Delete(temporaryPath);
		}
		catch (Exception exception) when (
			(exception is IOException) ||
			(exception is UnauthorizedAccessException) ||
			(exception is NotSupportedException))
		{
			// Best effort cleanup. The uniquely named temp file is never loaded as settings.
		}
	}

	private static Task TryDeleteTemporaryFileAsync(string temporaryPath)
	{
		return Task.Run(
			() => TryDeleteTemporaryFile(temporaryPath),
			CancellationToken.None);
	}

	private async Task VerifyFileHasNotChangedAsync(CancellationToken cancellationToken)
	{
		bool fileExists = await FileExistsAsync(_filePath, cancellationToken)
			.ConfigureAwait(false);

		if (fileExists != _loadedFileExisted)
		{
			throw new AccountProfileStoreException(
				UiText.Get("Persistence.AccountsChangedRestartRequired"));
		}

		if (!fileExists)
		{
			return;
		}

		byte[] currentFileContents = await ReadSettingsFileAsync(
			_filePath,
			cancellationToken);
		string currentFingerprint = ComputeFingerprint(currentFileContents);

		if (!string.Equals(
			currentFingerprint,
			_loadedFileFingerprint,
			StringComparison.Ordinal))
		{
			throw new AccountProfileStoreException(
				UiText.Get("Persistence.AccountsChangedRestartRequired"));
		}
	}

	private async Task VerifyBackupCanBeReplacedAsync(
		CancellationToken cancellationToken)
	{
		if (!await FileExistsAsync(BackupFilePath, cancellationToken)
				.ConfigureAwait(false))
		{
			return;
		}

		try
		{
			byte[] backupContents = await ReadSettingsFileAsync(
				BackupFilePath,
				cancellationToken);
			ParsedSettingsDocument backupDocument = ParseSettingsDocument(backupContents);

			if (backupDocument.SchemaVersion > CurrentSchemaVersion)
			{
				throw new AccountProfileStoreException(
					UiText.Get("Persistence.AccountsBackupNewerVersionRequired"));
			}
		}
		catch (OperationCanceledException)
		{
			throw;
		}
		catch (AccountProfileStoreException)
		{
			throw;
		}
		catch (Exception exception) when (
			(exception is JsonException) ||
			(exception is InvalidDataException) ||
			(exception is NotSupportedException))
		{
			// An invalid backup is not last-known-good and may be replaced by this valid save.
		}
	}

	private void BlockSaving(string message)
	{
		_canSave = false;
		_saveBlockedMessage = message;
	}

	private void EnableSaving()
	{
		_canSave = true;
		_saveBlockedMessage = null;
	}

	private void SetLoadedFileState(bool fileExisted, string? fingerprint)
	{
		_loadedFileExisted = fileExisted;
		_loadedFileFingerprint = fingerprint;
	}
